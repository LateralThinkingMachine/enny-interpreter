"""Embed the locked portable Rust/WASM build and browser adapter in one offline HTML file."""

import argparse
import base64
import hashlib
import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "standalone"
OUTPUT = SOURCE / "meeting-interpreter.html"
BINDINGS = ROOT / "apps" / "interpreter-ui" / "target" / "portable-bindgen"


def digest(data):
    return base64.b64encode(hashlib.sha256(data.encode("utf-8")).digest()).decode("ascii")


def render(bindings):
    glue = (bindings / "interpreter_ui.js").read_text(encoding="utf-8")
    wasm = (bindings / "interpreter_ui_bg.wasm").read_bytes()
    if not wasm.startswith(b"\0asm\x01\0\0\0"):
        raise ValueError("Invalid portable WebAssembly module")
    notices = (bindings / "NOTICES.txt").read_text(encoding="utf-8")
    if not notices.strip():
        raise ValueError("Portable runtime notices are empty")
    # Preserve the exact notice text in the DOM, including upstream line-end spacing.
    escaped_notices = re.sub(
        r"[ \t]+(?=\n)", lambda match: "".join(f"&#{ord(c)};" for c in match[0]), html.escape(notices)
    )
    encoded = base64.b64encode(wasm).decode("ascii")
    browser = (SOURCE / "browser-apis.js").read_text(encoding="utf-8")
    bootstrap = """
async function openPortableInterpreter(bytes) {
  const status = document.getElementById("load-status");
  try {
    const module = Uint8Array.from(atob(bytes), ch => ch.charCodeAt(0));
    await wasm_bindgen({ module_or_path: module });
    wasm_bindgen.mount_portable();
    status.remove();
  } catch {
    status.textContent = "The interpreter could not open. Enable WebAssembly in this browser or try desktop Chrome.";
  }
}
"""
    script = "\n" + browser + "\n" + glue + "\n" + bootstrap + f'openPortableInterpreter("{encoded}");\n'
    style = "\n" + (SOURCE / "portable.css").read_text(encoding="utf-8")
    if "</script" in script.lower() or "</style" in style.lower():
        raise ValueError("Inline payload contains an HTML closing tag")
    project_license = (ROOT / "LICENSE").read_text(encoding="utf-8")
    return f"""<!doctype html>
<!-- Generated by tools/build_portable_ui.py. Edit the Rust view, CSS or browser API adapter. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'sha256-{digest(script)}' 'wasm-unsafe-eval'; style-src 'sha256-{digest(style)}'; connect-src 'none'; base-uri 'none'; form-action 'none'">
<meta name="referrer" content="no-referrer">
<title>Enny · Meeting interpreter</title>
<style>{style}</style>
</head>
<body>
<div id="portable-root"></div>
<p id="load-status" role="status">Opening the interpreter…</p>
<noscript>Enable JavaScript and WebAssembly in this file to use the interpreter.</noscript>
<template id="runtime-notices"><pre>{escaped_notices}</pre></template>
<script>{script}</script>
</body>
<!--
Meeting Interpreter contributors. This standalone file is licensed under Apache-2.0.

{project_license}-->
</html>
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("bindings", type=Path, nargs="?", default=BINDINGS)
    parser.add_argument("--check", action="store_true", help="Fail if the checked-in download differs")
    args = parser.parse_args()
    result = render(args.bindings).encode("utf-8")
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != result:
            parser.exit(1, "Rebuild standalone/meeting-interpreter.html from the current portable WASM.\n")
    else:
        OUTPUT.write_bytes(result)


if __name__ == "__main__":
    main()
